-- Orders: header, lines and status history, created in one transaction by create_order.
-- Money is integer minor units in the order currency, except shipping_fee_minor, which is
-- in the tenant BASE currency like every stored fee (the pricing engine converts it with
-- exchange_rate). Pending orders (pending_shipping, pending_quote) have no totals and no
-- hold_expires_at, but they do hold their stock and slots.
-- Status changes are checked by a trigger (order_transition_allowed, same table as
-- src/lib/orders/states.ts) and each one is logged in order_events with the actor and
-- reason taken from the transaction settings app.order_actor and app.order_reason.
-- public_token is stored in plain text: it is 256 random bits generated by the server,
-- the owner (RLS) and the service role must be able to show the link again, and it only
-- unlocks one order of one tenant. anon has no access to any order table.
-- Errors raised by create_order (P0001, the message tells them apart):
-- too_many_pending_orders, product_unavailable, variant_required, start_required, plus
-- those of hold_stock and book_slot. 42501: tenant not active. 22023: malformed input.

-- Targets of same-tenant composite FKs.
alter table public.shipping_zones
  add constraint shipping_zones_id_tenant_key unique (id, tenant_id);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  public_token text not null unique check (public_token ~ '^[A-Za-z0-9_-]{43}$'),
  status text not null check (status in
    ('pending_shipping','pending_quote','awaiting_deposit','awaiting_review','confirmed','cancelled')),
  currency text not null check (currency ~ '^[A-Z]{3}$'),
  base_currency text not null check (base_currency ~ '^[A-Z]{3}$'),
  -- units of the base currency per 1 unit of `currency`; null when not converted by rate
  exchange_rate numeric check (exchange_rate is null or exchange_rate > 0),
  customer_name text not null check (length(btrim(customer_name)) between 1 and 120),
  -- normalized by the app: optional +, then digits only
  customer_phone text not null check (customer_phone ~ '^\+?[0-9]{7,15}$'),
  fields jsonb not null default '{}'::jsonb check (jsonb_typeof(fields) = 'object'),
  shipping_zone_id uuid,
  shipping_prepay boolean not null default false,
  shipping_fee_minor integer check (shipping_fee_minor is null or shipping_fee_minor >= 0),
  subtotal_minor integer not null check (subtotal_minor >= 0),
  total_minor integer check (total_minor is null or total_minor >= 0),
  deposit_due_minor integer check (deposit_due_minor is null or deposit_due_minor >= 0),
  due_on_delivery_minor integer check (due_on_delivery_minor is null or due_on_delivery_minor >= 0),
  hold_expires_at timestamptz,
  created_at timestamptz not null default now(),
  constraint orders_id_tenant_key unique (id, tenant_id),
  constraint orders_totals_match_status check (
    case
      when status in ('pending_shipping','pending_quote') then
        total_minor is null and deposit_due_minor is null and due_on_delivery_minor is null
      when status in ('awaiting_deposit','awaiting_review','confirmed') then
        total_minor is not null and deposit_due_minor is not null and due_on_delivery_minor is not null
        and total_minor = deposit_due_minor + due_on_delivery_minor
        and (status <> 'awaiting_deposit' or deposit_due_minor > 0)
      else true
    end),
  constraint orders_zone_fk foreign key (shipping_zone_id, tenant_id)
    references public.shipping_zones (id, tenant_id) on delete set null (shipping_zone_id)
);
create index orders_tenant_created_idx on public.orders(tenant_id, created_at desc);
create index orders_pending_phone_idx on public.orders(tenant_id, customer_phone)
  where status in ('pending_shipping','pending_quote','awaiting_deposit','awaiting_review');
create index orders_zone_idx on public.orders(shipping_zone_id, tenant_id) where shipping_zone_id is not null;

-- snapshot: what the customer ordered and the amounts the engine computed (unit, base,
-- extras, date, total, deposit definition and amount), so later steps never need the
-- catalog. Products and variants with orders cannot be deleted (deactivate them).
create table public.order_lines (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null,
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  position integer not null check (position > 0),
  product_id uuid not null,
  variant_id uuid,
  qty integer not null check (qty > 0),
  snapshot jsonb not null check (jsonb_typeof(snapshot) = 'object'),
  total_minor integer not null check (total_minor >= 0),
  constraint order_lines_order_fk foreign key (order_id, tenant_id)
    references public.orders (id, tenant_id) on delete cascade,
  constraint order_lines_product_fk foreign key (product_id, tenant_id)
    references public.products (id, tenant_id),
  constraint order_lines_variant_fk foreign key (variant_id, tenant_id)
    references public.product_variants (id, tenant_id)
);
create index order_lines_tenant_id_idx on public.order_lines(tenant_id);
create index order_lines_order_id_idx on public.order_lines(order_id, tenant_id);
create index order_lines_product_id_idx on public.order_lines(product_id, tenant_id);
create index order_lines_variant_id_idx on public.order_lines(variant_id, tenant_id) where variant_id is not null;

create table public.order_events (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null,
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  from_status text,
  to_status text not null,
  actor text not null check (length(actor) between 1 and 200),
  reason text check (reason is null or length(reason) <= 1000),
  -- clock time, so several changes in one transaction keep their order
  at timestamptz not null default clock_timestamp(),
  constraint order_events_order_fk foreign key (order_id, tenant_id)
    references public.orders (id, tenant_id) on delete cascade
);
create index order_events_tenant_id_idx on public.order_events(tenant_id);
create index order_events_order_id_idx on public.order_events(order_id, tenant_id, at);

